local M = {}

function M.get(name)
    return language[name or M.language()] or language.en
end

function M.menu(title, native)
    if M.language() == "ru" then
        local translated = language.ru.menu[title:gsub("&", "")]
        if translated then
            return native and translated or (translated:gsub("&", ""))
        end
    end
    return title
end


