local format_specifier = "%%%.?%d*[dfgs%%]"

local function template_pattern(text)
    local parts = { "^" }
    local position = 1
    while position <= #text do
        local start = text:find("%", position, true)
        local literal = text:sub(position, start and start - 1 or #text)
        parts[#parts + 1] = literal:gsub("([%(%)%.%%%+%-%*%?%[%]%^%$])", "%%%1")
        if not start then
            break
        end
        local specifier = text:sub(start):match("^" .. format_specifier)
        if specifier == "%%" then
            parts[#parts + 1] = "%%"
        elseif specifier:sub(-1) == "s" then
            parts[#parts + 1] = "(.-)"
        else
            parts[#parts + 1] = "([%d%.eE%+%-]+)"
        end
        position = start + #specifier
    end
    parts[#parts + 1] = "$"
    return table.concat(parts)
end

local translations = {}
local templates = {}
for _, message in ipairs(messages) do
    translations[message[1]] = message[2]
    if message[1]:find(format_specifier) then
        message.pattern = template_pattern(message[1])
        templates[#templates + 1] = message
    end
end
table.sort(templates, function(left, right)
    return #left[1] > #right[1]
end)

function M.language()
    local selected = mp.get_property_native("user-data/qplay-language", os.getenv("QPLAY_LANGUAGE") or "ru")
    return selected == "en" and "en" or "ru"
end

function M.localize(text)
    text = tostring(text or "")
    if M.language() == "ru" then
        return text
    end
    if translations[text] then
        return translations[text]
    end
    for _, message in ipairs(templates) do
        local values = { text:match(message.pattern) }
        if #values > 0 then
            local index = 0
            return (message[2]:gsub(format_specifier, function(specifier)
                if specifier == "%%" then
                    return "%"
                end
                index = index + 1
                local value = values[index]
                return specifier:sub(-1) == "s" and M.localize(value) or value
            end))
        end
    end
    return text
end

return M
